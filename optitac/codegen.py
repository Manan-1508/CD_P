"""
OptiTAC: Target Machine Code Generator
Translates optimized Three-Address Code (TAC) Quadruples into standard RISC-V (RV32I/M) assembly.
Integrates register allocation maps, spill management, and standard RISC-V calling conventions.
"""

from typing import List, Dict, Tuple, Optional
from optitac.ir import Quadruple
from optitac.regalloc import AllocationResult


class RISCVCodeGenerator:
    """
    Translates Intermediate TAC Quadruples into clean, compliant RISC-V assembly.
    Supports 32-bit registers, stack frame allocation for spilled temporaries,
    and standard RISC-V branch and arithmetic instructions.
    """

    def __init__(self, allocation: AllocationResult):
        self.alloc = allocation
        self.reg_map = allocation.reg_map
        self.spilled_vars = allocation.spilled_vars
        self.stack_offsets = allocation.stack_offsets
        self.frame_size = allocation.frame_size
        # Scratch registers for spill loads/stores and immediate materialization
        self.SCRATCH1 = "s0"
        self.SCRATCH2 = "s1"

    def _get_operand_reg(self, operand: str, scratch_reg: str, emitted: List[str]) -> str:
        """
        Resolves an operand to a physical register.
        If constant, loads into scratch_reg via 'li'.
        If spilled, loads from stack via 'lw'.
        If in register, returns the allocated register.
        """
        if Quadruple.is_constant(operand):
            emitted.append(f"    li {scratch_reg}, {operand}")
            return scratch_reg

        if operand in self.spilled_vars:
            offset = self.stack_offsets[operand]
            emitted.append(f"    lw {scratch_reg}, {offset}(sp)    # spill load {operand}")
            return scratch_reg

        return self.reg_map.get(operand, scratch_reg)

    def _store_result(self, dest: str, src_reg: str, emitted: List[str]):
        """
        Stores computation result into target variable location.
        If destination is spilled, emits 'sw' to stack offset.
        If in register and different, emits 'mv'.
        """
        if dest in self.spilled_vars:
            offset = self.stack_offsets[dest]
            emitted.append(f"    sw {src_reg}, {offset}(sp)    # spill store {dest}")
        else:
            dest_reg = self.reg_map.get(dest, self.SCRATCH1)
            if dest_reg != src_reg:
                emitted.append(f"    mv {dest_reg}, {src_reg}")

    def generate(self, instructions: List[Quadruple]) -> str:
        """Translates a list of TAC Quadruples into a complete RISC-V assembly file."""
        emitted: List[str] = []

        # Header Directives
        emitted.append("# ==============================================================================")
        emitted.append("#  Generated by OptiTAC (Intermediate Code Optimization Engine)")
        emitted.append("#  Target Architecture: RISC-V 32-bit (RV32I/M)")
        emitted.append(f"#  Allocated Registers: K = {self.alloc.k} | Frame Size: {self.frame_size} bytes")
        emitted.append("# ==============================================================================")
        emitted.append("    .text")
        emitted.append("    .globl main")
        emitted.append("    .type main, @function")
        emitted.append("main:")

        # Function Prologue
        # We save ra, s0, s1 in the top 12 bytes of the frame
        ra_off = self.frame_size - 4
        s0_off = self.frame_size - 8
        s1_off = self.frame_size - 12
        emitted.append(f"    addi sp, sp, -{self.frame_size}        # allocate stack frame")
        emitted.append(f"    sw ra, {ra_off}(sp)            # save return address")
        emitted.append(f"    sw s0, {s0_off}(sp)            # save scratch reg s0")
        emitted.append(f"    sw s1, {s1_off}(sp)            # save scratch reg s1")
        emitted.append("")

        for q in instructions:
            # Add comment with original TAC instruction
            emitted.append(f"    # TAC: {q.to_tac()}")

            if q.op == "LABEL":
                emitted.append(f"{q.arg1}:")

            elif q.op == "goto":
                emitted.append(f"    j {q.arg1}")

            elif q.op.startswith("if_"):
                self._translate_branch(q, emitted)

            elif q.op == "=":
                self._translate_copy(q, emitted)

            elif q.op.startswith("u"):
                self._translate_unary(q, emitted)

            elif q.op == "return":
                if q.arg1:
                    r1 = self._get_operand_reg(q.arg1, "a0", emitted)
                    if r1 != "a0":
                        emitted.append(f"    mv a0, {r1}")
                else:
                    emitted.append("    li a0, 0")
                emitted.append("    j .L_epilogue")

            elif q.op in {"+", "-", "*", "/", "%", "&", "|", "^", "<<", ">>"}:
                self._translate_binary_op(q, emitted)

            else:
                emitted.append(f"    # [UNHANDLED OP: {q.op}]")

            emitted.append("")

        # Function Epilogue
        emitted.append(".L_epilogue:")
        emitted.append(f"    lw s1, {s1_off}(sp)            # restore scratch reg s1")
        emitted.append(f"    lw s0, {s0_off}(sp)            # restore scratch reg s0")
        emitted.append(f"    lw ra, {ra_off}(sp)            # restore return address")
        emitted.append(f"    addi sp, sp, {self.frame_size}         # deallocate stack frame")
        emitted.append("    ret                           # return to caller")

        return "\n".join(emitted)

    def _translate_copy(self, q: Quadruple, emitted: List[str]):
        """Translates copy/assignment instruction (x = y or x = 10)."""
        dest = q.res
        src = q.arg1
        if src is None:
            return

        target_reg = self.reg_map.get(dest, self.SCRATCH1) if dest not in self.spilled_vars else self.SCRATCH1

        if Quadruple.is_constant(src):
            emitted.append(f"    li {target_reg}, {src}")
        else:
            src_reg = self._get_operand_reg(src, self.SCRATCH2, emitted)
            if target_reg != src_reg:
                emitted.append(f"    mv {target_reg}, {src_reg}")

        if dest in self.spilled_vars:
            offset = self.stack_offsets[dest]
            emitted.append(f"    sw {target_reg}, {offset}(sp)    # spill store {dest}")

    def _translate_unary(self, q: Quadruple, emitted: List[str]):
        """Translates unary instructions (e.g. u-, u!)."""
        dest = q.res
        arg = q.arg1
        target_reg = self.reg_map.get(dest, self.SCRATCH1) if dest not in self.spilled_vars else self.SCRATCH1
        r1 = self._get_operand_reg(arg, self.SCRATCH2, emitted)

        u_op = q.op[1:]
        if u_op == "-":
            emitted.append(f"    neg {target_reg}, {r1}")
        elif u_op == "!":
            emitted.append(f"    seqz {target_reg}, {r1}")
        else:
            emitted.append(f"    mv {target_reg}, {r1}")

        if dest in self.spilled_vars:
            offset = self.stack_offsets[dest]
            emitted.append(f"    sw {target_reg}, {offset}(sp)    # spill store {dest}")

    def _translate_binary_op(self, q: Quadruple, emitted: List[str]):
        """Translates binary operations (+, -, *, /, etc.)."""
        dest = q.res
        arg1, arg2 = q.arg1, q.arg2
        target_reg = self.reg_map.get(dest, self.SCRATCH1) if dest not in self.spilled_vars else self.SCRATCH1

        # Check for immediate form (e.g., x + 5)
        if q.op == "+" and Quadruple.is_constant(arg2):
            r1 = self._get_operand_reg(arg1, self.SCRATCH1, emitted)
            emitted.append(f"    addi {target_reg}, {r1}, {arg2}")
            self._store_result(dest, target_reg, emitted)
            return

        r1 = self._get_operand_reg(arg1, self.SCRATCH1, emitted)
        r2 = self._get_operand_reg(arg2, self.SCRATCH2, emitted)

        op_map = {
            "+": "add",
            "-": "sub",
            "*": "mul",
            "/": "div",
            "%": "rem",
            "&": "and",
            "|": "or",
            "^": "xor",
            "<<": "sll",
            ">>": "sra",
        }
        inst = op_map.get(q.op, "add")
        emitted.append(f"    {inst} {target_reg}, {r1}, {r2}")
        self._store_result(dest, target_reg, emitted)

    def _translate_branch(self, q: Quadruple, emitted: List[str]):
        """Translates conditional branch instructions."""
        relop = q.op.replace("if_", "")
        target = q.res

        if relop == "true":
            r1 = self._get_operand_reg(q.arg1, self.SCRATCH1, emitted)
            emitted.append(f"    bnez {r1}, {target}")
            return
        elif relop == "false":
            r1 = self._get_operand_reg(q.arg1, self.SCRATCH1, emitted)
            emitted.append(f"    beqz {r1}, {target}")
            return

        r1 = self._get_operand_reg(q.arg1, self.SCRATCH1, emitted)
        r2 = self._get_operand_reg(q.arg2, self.SCRATCH2, emitted)

        branch_map = {
            "==": f"beq {r1}, {r2}, {target}",
            "!=": f"bne {r1}, {r2}, {target}",
            "<":  f"blt {r1}, {r2}, {target}",
            "<=": f"bge {r2}, {r1}, {target}",  # swapped
            ">":  f"blt {r2}, {r1}, {target}",  # swapped
            ">=": f"bge {r1}, {r2}, {target}",
        }
        inst = branch_map.get(relop, f"beq {r1}, {r2}, {target}")
        emitted.append(f"    {inst}")
